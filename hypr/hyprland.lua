-- See https://wiki.hypr.land/configuring/core/autostart/

-- Autostart necessary processes (like notifications daemons, status bars, etc.)
-- Or execute your favorite apps at launch like this:
--
-- Runs once per compositor session, never on a config reload.
hl.on("hyprland.start", function()
    hl.exec_cmd("dbus-update-activation-environment --systemd WAYLAND_DISPLAY XDG_CURRENT_DESKTOP")
    hl.exec_cmd("systemctl --user import-environment WAYLAND_DISPLAY XDG_CURRENT_DESKTOP")
    hl.exec_cmd("~/.local/bin/desktop-bar.sh ensure")
    hl.exec_cmd("solaar --window=hide")
    hl.exec_cmd("~/.local/bin/restore-wallpaper.sh")
    hl.exec_cmd("/usr/lib/polkit-gnome/polkit-gnome-authentication-agent-1")
    hl.exec_cmd("pactl load-module module-null-sink sink_name=DM_Mixer sink_properties=device.description=DM_Mixer")
    hl.exec_cmd("pw-metadata -n settings 0 clock.force-rate 48000")
end)


-- On reload, recover a missing bar or refresh it after its config changes.
hl.on("config.reloaded", function()
    hl.exec_cmd("~/.local/bin/desktop-bar.sh ensure")
end)

